from flask import Blueprint, jsonify, request, send_file
from flask_jwt_extended import jwt_required, get_jwt_identity
from src.models.user import User
from src.pdf.notice_builder import NOTICES, notice_types, build_notice_pdf
from datetime import datetime
import logging
import io

notices_bp = Blueprint('notices', __name__)
logger = logging.getLogger(__name__)


def require_admin():
    """Helper function to require admin role."""
    try:
        current_user_id = get_jwt_identity()
        user = User.query.get(current_user_id)
        if not user or user.role not in ['admin', 'manager']:
            return None
        return user
    except Exception:
        return None


@notices_bp.route('/admin/notices/types', methods=['GET'])
@jwt_required()
def list_notice_types():
    """The notices that can be generated, with the questions each one asks."""
    user = require_admin()
    if not user:
        return jsonify({"error": "Forbidden"}), 403

    return jsonify({'notices': notice_types()}), 200


@notices_bp.route('/admin/notices/generate', methods=['POST'])
@jwt_required()
def generate_notice():
    """Generate a notice PDF from a notice type and the answers to its questions."""
    try:
        user = require_admin()
        if not user:
            return jsonify({"error": "Forbidden"}), 403

        data = request.get_json() or {}
        notice = NOTICES.get(data.get('type'))
        if not notice:
            return jsonify({"error": "Unknown notice type"}), 400
        if not notice.get('sections'):
            return jsonify({"error": f"The wording for the {notice['label']} has not been added yet"}), 400

        answers = data.get('values') if isinstance(data.get('values'), dict) else {}
        values = {}
        for field in notice['fields']:
            value = str(answers.get(field['name']) or '').strip()
            if not value:
                return jsonify({"error": f"{field['label']} is required"}), 400
            if len(value) > field['max']:
                return jsonify({"error": f"{field['label']} is too long"}), 400
            if field['type'] == 'date':
                try:
                    datetime.strptime(value, '%Y-%m-%d')
                except ValueError:
                    return jsonify({"error": f"{field['label']} is not a valid date"}), 400
            values[field['name']] = value

        buffer = io.BytesIO()
        filename = build_notice_pdf(buffer, data['type'], values)
        buffer.seek(0)

        logger.info(f"{notice['label']} generated by admin {user.id}")
        return send_file(
            buffer,
            mimetype='application/pdf',
            as_attachment=True,
            download_name=f'{filename}.pdf'
        )

    except Exception as e:
        logger.error(f"Error generating notice: {e}")
        return jsonify({"error": "Failed to generate notice"}), 500
